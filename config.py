import numpy as np

# =================================================================
# --- 1. Параметры Симуляции (PyBullet) ---
# =================================================================
GUI_MODE = True           # Включить GUI (True) или обучать "вслепую" (False)
SIM_TIMESTEP = 20 / 240.0 # Шаг времени симуляции (стандарт для PyBullet)
MAX_EPISODE_STEPS = 250  #Макс. шагов в одном эпизоде (по заданию 200-300)

# =================================================================
# --- 2. Параметры Среды (Робот и Цель) ---
# =================================================================
PLANE_URDF_PATH = "plane.urdf"
ROBOT_URDF_PATH = "husky/husky.urdf" # Убедись, что PyBullet может найти этот файл

# Индексы суставов колес для r2d2.urdf
# ВНИМАНИЕ: Они могут отличаться в твоей версии URDF!
# Это самые частые значения для стандартной модели r2d2.
# Мы будем управлять только двумя "главными" колесами.
LEFT_WHEEL_JOINT_INDEX = 2
RIGHT_WHEEL_JOINT_INDEX = 3

# Максимальное усилие, которое могут развить колеса
# (чтобы робот не "улетал" при старте)
MAX_WHEEL_FORCE = 1000 
# Максимальная скорость спавна цели (от -X до +X и от -Y до +Y)
MAX_TARGET_SPAWN_RADIUS = 1.5

# =================================================================
# --- 3. Параметры Действий (Actions) ---
# =================================================================
# Определяем 5 дискретных действий, как в задании.
# Каждое действие - это пара скоростей (v_left, v_right)
BASE_SPEED = 6.0 # Базовая скорость для движения
TURN_SPEED = 3.0 # Скорость для поворота

ACTIONS_MAP = {
    0: (BASE_SPEED, BASE_SPEED),     # 0: Вперед
    1: (-BASE_SPEED, -BASE_SPEED),   # 1: Назад
    2: (-TURN_SPEED, TURN_SPEED),    # 2: Влево (разворот на месте)
    3: (TURN_SPEED, -TURN_SPEED),    # 4: Вправо (разворот на месте)
    4: (0, 0)                        # 5: Стоять
}
NUM_ACTIONS = len(ACTIONS_MAP)

# =================================================================
# --- 4. Параметры Состояния (State Discretization) ---
# =================================================================
# Q-таблица не может работать с "плавающими" числами (типа 1.2345).
# Мы "нарежем" непрерывное пространство (дистанция, угол) на "корзины" (bins).

# Дистанция: [Очень близко, ... , Очень далеко]
NUM_DISTANCE_BINS = 10
# Угол до цели: [Резко слева, ... , Прямо, ... , Резко справа]
NUM_ANGLE_BINS = 10

# Диапазоны значений для нарезки
# Дистанция: от 0 до MAX_TARGET_SPAWN_RADIUS * 1.5 (с запасом)
MAX_STATE_DISTANCE = MAX_TARGET_SPAWN_RADIUS * 1.5
# Угол: от -PI до +PI
MAX_STATE_ANGLE = np.pi 

# Итоговый размер Q-таблицы будет (NUM_DISTANCE_BINS, NUM_ANGLE_BINS, NUM_ACTIONS)

# =================================================================
# --- 5. Параметры Обучения (Q-Learning) ---
# =================================================================
NUM_EPISODES = 1000      # Количество эпизодов для обучения
ALPHA = 0.5             # (α) Скорость обучения (learning rate)
GAMMA = 0.99             # (γ) Фактор дисконтирования (важность будущих наград)

EPSILON_START = 1.0      # Начальный шанс "исследования" (exploration)
EPSILON_END = 0.01       # Минимальный шанс "исследования"
# За сколько эпизодов эпсилон снизится от START до END
EPSILON_DECAY_DURATION = NUM_EPISODES * 0.75 

# =================================================================
# --- 6. Параметры Награды (Rewards) ---
# =================================================================
# Формула: R = -(dist_new - dist_old) - 0.01 * turn_penalty + Bonus
# Награда за приближение - это -(dist_new - dist_old). 
# Если dist_new < dist_old, награда положительная.

REACH_GOAL_BONUS = 10.0   # (Бонус +10) Награда за достижение цели
DISTANCE_THRESHOLD = 0.3  # (distance < 0.3) Как близко нужно подобраться


# Штраф за избыточные маневры (повороты)
# (0.01 × turn_penalty)
TURN_PENALTY_FACTOR = 0.01
STEP_PENALTY = 0.0